--
-- Workspaces: separate branches or businesses in one HDH CRM.
--
-- Every contact, company, deal, note, task and tag belongs to one workspace.
-- The app sends the workspace it is showing in the X-Workspace-Id header, and
-- the row level security policies only return (and only accept) rows of that
-- workspace. Administrators can open every workspace; other users only the
-- workspaces they are members of.
--
-- The existing data becomes the first workspace, "Main workspace", which every
-- existing user can open.
--

create table public.workspaces (
    id bigint generated by default as identity primary key,
    name text not null,
    created_at timestamp with time zone not null default now(),
    constraint workspaces_name_length check (char_length(btrim(name)) between 1 and 80)
);

create table public.workspace_members (
    workspace_id bigint not null references public.workspaces(id) on delete cascade,
    sales_id bigint not null references public.sales(id) on delete cascade,
    created_at timestamp with time zone not null default now(),
    primary key (workspace_id, sales_id)
);

create index workspace_members_sales_id_idx on public.workspace_members (sales_id);

insert into public.workspaces (name) values ('Main workspace');

insert into public.workspace_members (workspace_id, sales_id)
select (select min(id) from public.workspaces), id from public.sales;

--
-- Access helpers
--

-- Whether this user may open this workspace: administrators open every
-- workspace, others the ones they are members of. Disabled users open none.
-- It does not look the workspace up: a workspace being created is not visible
-- yet to the policy checking it (INSERT ... RETURNING).
create or replace function public.user_can_access_workspace(workspace bigint, uid uuid) returns boolean
    language sql stable security definer
    set search_path to ''
    as $$
  select exists (
    select 1
    from public.sales s
    where s.user_id = uid
      and not s.disabled
      and (
        s.administrator
        or exists (
          select 1 from public.workspace_members m
          where m.workspace_id = workspace and m.sales_id = s.id
        )
      )
  );
$$;

-- The workspace of the current request: the one named in the X-Workspace-Id
-- header if the user may open it (no workspace at all otherwise, so no rows),
-- or, without the header, the first workspace the user may open.
create or replace function public.current_workspace_id() returns bigint
    language plpgsql stable security definer
    set search_path to ''
    as $$
declare
  requested text := nullif(current_setting('request.headers', true), '')::json ->> 'x-workspace-id';
  uid uuid := auth.uid();
  workspace bigint;
begin
  if uid is null then
    -- No signed-in user (server code, maintenance, tests): the first workspace
    select min(w.id) into workspace from public.workspaces w;
    return workspace;
  end if;
  if requested ~ '^[0-9]{1,18}$' then
    workspace := requested::bigint;
    if public.user_can_access_workspace(workspace, uid) then
      return workspace;
    end if;
    return null;
  end if;
  select w.id into workspace
  from public.workspaces w
  where public.user_can_access_workspace(w.id, uid)
  order by w.id
  limit 1;
  return workspace;
end;
$$;

grant execute on function public.user_can_access_workspace(bigint, uuid) to authenticated;
grant execute on function public.current_workspace_id() to authenticated, anon;

--
-- A workspace for every record, and policies scoped to the current workspace
--

do $$
declare
  t text;
  r record;
  first_workspace bigint := (select min(id) from public.workspaces);
begin
  foreach t in array array['companies', 'contacts', 'contact_notes', 'deals', 'deal_notes', 'tags', 'tasks'] loop
    -- A constant default puts the existing rows in the first workspace without
    -- rewriting the table or firing its triggers; new rows then default to the
    -- workspace of the request.
    execute format('alter table public.%I add column workspace_id bigint not null default %s', t, first_workspace);
    execute format('alter table public.%I alter column workspace_id set default public.current_workspace_id()', t);
    execute format(
      'alter table public.%I add constraint %I foreign key (workspace_id) references public.workspaces(id) on delete %s',
      t, t || '_workspace_id_fkey',
      -- Tags are only labels: they go with their workspace. Anything else
      -- keeps a workspace from being deleted.
      case when t = 'tags' then 'cascade' else 'restrict' end
    );
    execute format('create index %I on public.%I (workspace_id)', t || '_workspace_id_idx', t);

    for r in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on public.%I', r.policyname, t);
    end loop;
    execute format(
      'create policy "Workspace read" on public.%I for select to authenticated using (workspace_id = (select public.current_workspace_id()))', t);
    execute format(
      'create policy "Workspace insert" on public.%I for insert to authenticated with check (workspace_id = (select public.current_workspace_id()))', t);
    execute format(
      'create policy "Workspace update" on public.%I for update to authenticated using (workspace_id = (select public.current_workspace_id())) with check (workspace_id = (select public.current_workspace_id()))', t);
    execute format(
      'create policy "Workspace delete" on public.%I for delete to authenticated using (workspace_id = (select public.current_workspace_id()))', t);
  end loop;
end
$$;

-- Notes and tasks always live in the workspace of their contact or deal
create or replace function public.set_workspace_from_parent() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
begin
  if tg_table_name in ('contact_notes', 'tasks') then
    select c.workspace_id into new.workspace_id from public.contacts c where c.id = new.contact_id;
  elsif tg_table_name = 'deal_notes' then
    select d.workspace_id into new.workspace_id from public.deals d where d.id = new.deal_id;
  end if;
  return new;
end;
$$;

create trigger "05_contact_notes_workspace"
    before insert or update of contact_id on public.contact_notes
    for each row execute function public.set_workspace_from_parent();

create trigger "05_tasks_workspace"
    before insert or update of contact_id on public.tasks
    for each row execute function public.set_workspace_from_parent();

create trigger "05_deal_notes_workspace"
    before insert or update of deal_id on public.deal_notes
    for each row execute function public.set_workspace_from_parent();

-- A contact or a deal cannot point to a company of another workspace
create or replace function public.check_company_workspace() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
begin
  if new.company_id is not null and exists (
    select 1 from public.companies c
    where c.id = new.company_id and c.workspace_id <> new.workspace_id
  ) then
    raise exception 'This company belongs to another workspace' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger "05_contacts_company_workspace"
    before insert or update of company_id, workspace_id on public.contacts
    for each row execute function public.check_company_workspace();

create trigger "05_deals_company_workspace"
    before insert or update of company_id, workspace_id on public.deals
    for each row execute function public.check_company_workspace();

-- There is always at least one workspace
create or replace function public.prevent_deleting_last_workspace() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
begin
  if (select count(*) from public.workspaces) <= 1 then
    raise exception 'The last workspace cannot be deleted' using errcode = '23514';
  end if;
  return old;
end;
$$;

create trigger workspaces_keep_one
    before delete on public.workspaces
    for each row execute function public.prevent_deleting_last_workspace();

--
-- Workspaces and memberships
--

alter table public.workspaces enable row level security;
alter table public.workspace_members enable row level security;

create policy "Members see their workspaces" on public.workspaces
    for select to authenticated
    using (public.user_can_access_workspace(id, (select auth.uid())));
create policy "Admins create workspaces" on public.workspaces
    for insert to authenticated with check ((select public.is_admin()));
create policy "Admins rename workspaces" on public.workspaces
    for update to authenticated
    using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins delete workspaces" on public.workspaces
    for delete to authenticated using ((select public.is_admin()));

create policy "Admins and the member see memberships" on public.workspace_members
    for select to authenticated
    using (
      (select public.is_admin())
      or sales_id = (select s.id from public.sales s where s.user_id = (select auth.uid()))
    );
create policy "Admins add members" on public.workspace_members
    for insert to authenticated with check ((select public.is_admin()));
create policy "Admins remove members" on public.workspace_members
    for delete to authenticated using ((select public.is_admin()));

grant select, insert, update, delete on table public.workspaces to authenticated;
grant select, insert, delete on table public.workspace_members to authenticated;
grant usage, select on sequence public.workspaces_id_seq to authenticated;

-- Chooses the members of a workspace in one call (administrators only)
create or replace function public.set_workspace_members(target_workspace bigint, member_ids bigint[]) returns void
    language plpgsql
    set search_path to ''
    as $$
begin
  if not public.is_admin() then
    raise exception 'Only administrators can choose workspace members' using errcode = '42501';
  end if;
  delete from public.workspace_members m
  where m.workspace_id = target_workspace
    and not (m.sales_id = any (coalesce(member_ids, '{}'::bigint[])));
  insert into public.workspace_members (workspace_id, sales_id)
  select target_workspace, member_id
  from unnest(coalesce(member_ids, '{}'::bigint[])) as member_id
  on conflict do nothing;
end;
$$;

grant execute on function public.set_workspace_members(bigint, bigint[]) to authenticated;

-- One row per workspace the signed-in user can open, with its size. It runs
-- with its owner's rights (security_invoker off) so the counts cover every
-- workspace, not just the current one; the where clause keeps the list to the
-- workspaces this user may open.
create view public.workspaces_summary with (security_invoker = off) as
select
    w.id,
    w.name,
    w.created_at,
    (select count(*) from public.contacts c where c.workspace_id = w.id) as nb_contacts,
    (select count(*) from public.companies c where c.workspace_id = w.id) as nb_companies,
    (select count(*) from public.deals d where d.workspace_id = w.id and d.archived_at is null) as nb_deals,
    (
      select coalesce(array_agg(m.sales_id order by m.sales_id), '{}'::bigint[])
      from public.workspace_members m
      where m.workspace_id = w.id
    ) as member_ids
from public.workspaces w
where public.user_can_access_workspace(w.id, auth.uid());

grant select on table public.workspaces_summary to authenticated;
